BEGIN;

CREATE TYPE line_type AS ENUM ('BUS', 'TRAM');

CREATE TABLE stops
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT    NOT NULL,
    lat           REAL    NOT NULL,
    lon           REAL    NOT NULL,
    has_screen    BOOLEAN NOT NULL,
    is_on_request BOOLEAN NOT NULL
);

CREATE TABLE lines
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number     TEXT      NOT NULL,
    type       line_type NOT NULL,
    is_express BOOLEAN   NOT NULL
);

CREATE TABLE calendar
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monday     BOOLEAN NOT NULL,
    tuesday    BOOLEAN NOT NULL,
    wednesday  BOOLEAN NOT NULL,
    thursday   BOOLEAN NOT NULL,
    friday     BOOLEAN NOT NULL,
    saturday   BOOLEAN NOT NULL,
    sunday     BOOLEAN NOT NULL,
    start_date DATE    NOT NULL,
    end_date   DATE    NOT NULL
);

CREATE TABLE exception_types
(
    id          SMALLINT PRIMARY KEY,
    description TEXT NOT NULL
);

CREATE TABLE calendar_dates
(
    id             BIGINT   NOT NULL REFERENCES calendar (id),
    date           DATE     NOT NULL,
    exception_type SMALLINT NOT NULL REFERENCES exception_types (id),
    PRIMARY KEY (id, date)
);

CREATE TABLE trips
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_id       BIGINT NOT NULL REFERENCES lines (id),
    start_stop_id BIGINT NOT NULL REFERENCES stops (id),
    end_stop_id   BIGINT NOT NULL REFERENCES stops (id),
    headsign      TEXT   NOT NULL,
    calendar_id   BIGINT NOT NULL REFERENCES calendar (id)
);

CREATE TABLE connections
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_stop_id  BIGINT  NOT NULL REFERENCES stops (id),
    end_stop_id    BIGINT  NOT NULL REFERENCES stops (id),
    departure_time TIME    NOT NULL,
    arrival_time   TIME    NOT NULL,
    trip_id        BIGINT  NOT NULL REFERENCES trips (id),
    sequence_num   INTEGER NOT NULL
);

CREATE TABLE drivers
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name     TEXT    NOT NULL,
    last_name      TEXT    NOT NULL,
    birth_date     DATE    NOT NULL,
    license_number TEXT    NOT NULL UNIQUE,
    is_active      BOOLEAN NOT NULL
);

CREATE TABLE vehicles
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fleet_number        TEXT    NOT NULL UNIQUE,
    make                TEXT    NOT NULL,
    model               TEXT    NOT NULL,
    production_year     INTEGER NOT NULL,
    registration_number TEXT    NOT NULL UNIQUE,
    capacity            INTEGER NOT NULL,
    is_low_floor        BOOLEAN NOT NULL,
    notes               TEXT
);

CREATE TABLE trip_executions
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id           BIGINT NOT NULL REFERENCES trips (id),
    driver_id         BIGINT NOT NULL REFERENCES drivers (id),
    vehicle_id        BIGINT NOT NULL REFERENCES vehicles (id),
    service_date      DATE   NOT NULL,
    actual_start_time TIMESTAMP,
    actual_end_time   TIMESTAMP
);

COMMIT;
